/**
Пара совместимых версий из подготовленного результата; извлекается предоставленной функцией `versions`.

@property platform - Непрозрачный идентификатор готовой платформы, для которой подготовлена оболочка.

@property web - Непрозрачный идентификатор версии оболочки для указанной платформы.
Идентификаторы формирует владелец артефактов; Web сохраняет их без интерпретации.
*/
export type Version = Readonly<{platform: string, web: string}>

/**
Неизменяемый снимок общей операции Web, получаемый чтением и подпиской.

@property operationId - UUID текущей или последней операции; до первой подготовки равен `null`.
Конкурентные запросы одной операции наблюдают один идентификатор.

@property phase - `idle` до запуска; `preparing` во время подготовки; `prepared` после получения версий;
`publishing` перед вызовом публикации; `published` после его возврата; `failed` при ошибке или отмене.
`published` не подтверждает, что открытые страницы уже применили выпуск.

@property at - Время создания снимка в формате ISO 8601 UTC; обновляется при каждом переходе состояния.

@property versions - Пары {@link Version} последнего успешно подготовленного результата, изначально пустой массив.
Версии появляются до публикации; при ошибке сохраняется последний доступный список.

@property error - Сообщение ошибки начавшейся операции либо `null`.
Начало новой подготовки очищает предыдущую ошибку; отдельное состояние отмены не вводится.
*/
export type State = Readonly<{
  operationId: string | null
  phase: "idle" | "preparing" | "prepared" | "publishing" | "published" | "failed"
  at: string
  versions: readonly Version[]
  error: string | null
}>
