import type {State, Version} from "./release"

/**
Типовой контракт подготовки и публикации Web-интерфейса в готовой платформе.

- {@link Zavx0zStorybookAppWebRelease.Input} описывает предоставленные вызывающим кодом `prepare`, `versions` и `publish`.
  Параметр `Prepared` сохраняет конкретный тип подготовленных артефактов между этими функциями.
- {@link Zavx0zStorybookAppWebRelease.Output} описывает `rebuild`, `read`, `subscribe` и `dispose` для управления
  общей операцией. Наблюдатели получают {@link State}, а не сами подготовленные артефакты.

Аргументы, результаты, ошибки и жизненный цикл членов собраны в родительских
описаниях `Input` и `Output`.
*/
export declare namespace Zavx0zStorybookAppWebRelease {
  /**
  Вызывающий код предоставляет три функции для подготовки и публикации Web.
  Web управляет порядком их вызовов и общим состоянием операции.

  @typeParam Prepared - Результат предоставленной функции `prepare` после `await`.
  Его форму определяет вызывающий код. Web передаёт это значение без преобразования
  в `versions` и `publish`; внутренние поля результата ему не нужны.
  Наблюдателям передаётся состояние с версиями {@link Version}.

  @property prepare - Подготавливает артефакты Web для совместимой готовой платформы по запросу `rebuild`.
  Аргумент `signal` принадлежит времени жизни Web и отменяется при `dispose`;
  отключение отдельного наблюдателя не отменяет подготовку. Возвращаемый Promise
  содержит `Prepared` для последующих вызовов `versions` и `publish`.
  Ошибка подготовки или отмены отклоняет Promise операции Web и переводит её в `failed`.

  @property versions - Извлекает версии оболочек и платформ из подготовленных артефактов.
  Аргумент `prepared` — то же значение, которое вернула `prepare` после `await`.
  Возвращаемый список Web копирует в наблюдаемое состояние до публикации.
  Ошибка извлечения версий прерывает операцию до публикации и переводит её в `failed`.

  @property publish - Синхронно публикует артефакты при запросе `rebuild({apply: true})`.
  Аргумент `prepared` — то же значение, из которого `versions` уже извлекла версии.
  После успешного возврата Web отмечает операцию как `published`; доставка и применение
  в открытых страницах подтверждаются HMR отдельно. Ошибка отклоняет Promise операции
  и переводит её в `failed`; Web не откатывает побочные эффекты предоставленной функции.

  @example
  Передача одного подготовленного значения внутри Web:
  ```ts
  const candidate = await input.prepare(signal)
  const versions = input.versions(candidate)
  // При запросе применения:
  input.publish(candidate)
  ```
  */
  export type Input<Prepared> = Readonly<{
    prepare(signal: AbortSignal): Promise<Prepared>
    versions(prepared: Prepared): readonly Version[]
    publish(prepared: Prepared): void
  }>

  /**
  Управление общей операцией выпуска Web и её временем жизни.
  Подписчики наблюдают {@link State}; подготовленные артефакты остаются внутри
  взаимодействия с функциями {@link Input}.

  @property rebuild - Запускает подготовку; конкурентные обращения получают один Promise текущей операции.
  Аргумент `options` с `apply: true` запрашивает публикацию подготовленных артефактов.
  Без `apply` или с `false` запрос ограничивается подготовкой, если другой участник общей
  операции не запросил публикацию; `false` не отменяет уже запрошенное применение.
  Promise возвращает снимок состояния на момент завершения. Ошибка любой функции
  {@link Input} или отмена отклоняет Promise и сохраняется в состоянии `failed`.
  После `dispose` новый запрос отклоняется с ошибкой завершения приложения.
  После завершения предыдущей операции следующий вызов начинает новую подготовку.

  @property read - Возвращает последнее состояние без запуска подготовки.
  Аргументов нет; возвращается текущий неизменяемый снимок {@link State}.
  Каждое обновление создаёт новый снимок.

  @property subscribe - Подключает наблюдателя и синхронно передаёт ему текущий снимок.
  Аргумент `listener` получает текущее состояние сразу и последующие обновления.
  Возвращаемая функция удаляет эту подписку без отмены общей подготовки.
  Исключение при первом вызове удаляет подписку; исключения при дальнейших уведомлениях
  подавляются и не останавливают операцию или остальных наблюдателей.

  @property dispose - Запрещает новые операции, отменяет общий сигнал и после ожидания очищает подписки.
  Аргументов нет; Promise завершается после текущей операции, её ошибка при ожидании подавляется.
  Если `prepare` не реагирует на сигнал, ожидание продолжается до завершения её Promise.
  Повторный вызов допустим.

  @example
  ```ts
  const unsubscribe = web.subscribe(state => console.log(state.phase))
  try {
    await web.rebuild({apply: true})
  } finally {
    unsubscribe()
    await web.dispose()
  }
  ```
  */
  export type Output = Readonly<{
    rebuild(options?: Readonly<{apply?: boolean}>): Promise<State>
    read(): State
    subscribe(listener: (state: State) => void): () => void
    dispose(): Promise<void>
  }>
}
