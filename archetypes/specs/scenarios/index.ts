/**
Сценарий — это **структурированная исполняемая документация**, которая раскрывает
назначение, возможности, правила использования и ограничения функции, компонента
или другой сущности.

Он даёт целостное понимание предмета: что существует, для чего предназначено,
в каких условиях применяется, какие данные принимает, что возвращает или изменяет
и какой смысл имеют полученные результаты. По сценарию можно разобраться
в использовании сущности и понять требования к её поведению, не изучая всю
внутреннюю реализацию.

Документация раскрывается последовательно: общая картина разделяется на варианты
использования, внутри вариантов связанные вопросы объединяются по темам,
а каждая тема раскрывается конкретными примерами и проверками. Глубина описания
определяется смыслом — подробности появляются там, где они помогают понять
отдельное свойство, условие или связь.

Названия обозначают предмет рассмотрения, короткие описательные формулировки
объясняют его назначение, а фактические данные показывают, что происходит
при выполнении. Требования и ограничения выражаются проверяемыми условиями.
Если условие нарушено, видно не только различие между ожидаемым и полученным,
но и смысл нарушенного требования.

Таким образом, **один и тот же сценарий одновременно объясняет поведение
и проверяет его**. Примеры исполняются, результаты получаются из реальной работы,
а проверки подтверждают соответствие описанным правилам. Это помогает замечать
расхождения при изменении реализации.

Основное содержание документации находится в самих примерах, проверках
и их организации. Отдельный текст используется минимально — для важных пояснений,
которые невозможно достаточно ясно выразить таким способом. Не требуется
поддерживать рядом ещё одно независимое изложение тех же правил.

Сценарий понятен человеку и агенту и может служить общим источником для проверки,
изучения и представления знаний о сущности. При этом автор пишет привычный
сценарный тест и сосредоточивается на функционале: ему не требуется знать
устройство инструментов, которые впоследствии будут использовать эти данные.

Сценарий компонента объявляет JSX с props непосредственно в единственном аргументе
`render`. Приложение связывает эту же декларацию с выполненными вариантами
и пунктами, объясняющими поведение. Фикстуры могут содержать исходные данные;
обёртка компонента ради представления в Storybook не требуется.

Руководство и все правила авторства раскрыты в [исполняемом сценарии](spec/scenario.spec.ts).
`readScenarioGuide` принимает путь к примеру и показывает его файлы, код и проверки.

@packageDocumentation
*/
import {basename, dirname, resolve} from "node:path"
import {readScenario} from "@storybook/app/scenarios"
import {createScenarioGuide} from "../shared/scenario-guide"
import type {ReadScenarioGuideInput} from "./contract/input"
import type {ReadScenarioGuideOutput} from "./contract/output"

export type {ReadScenarioGuideInput, ReadScenarioGuideOutput}

/**
Читает указанный сценарий через App и собирает руководство его написания.
Связанные файлы определяет рядом со сценарием; передавать технический отчёт не требуется.

@param input - Путь к файлу сценария его непосредственного владельца.
@returns Файлы примера, исходный код и результаты проверки сценария.
@throws TypeError, если путь не указывает на spec/scenario.spec.ts либо spec/scenario.spec.tsx.
@throws Ошибки чтения и запуска сценария из App.
*/
export async function readScenarioGuide({path}: ReadScenarioGuideInput): Promise<ReadScenarioGuideOutput> {
  const source = resolve(path)
  if (basename(dirname(source)) !== "spec" || !/^scenario\.spec\.tsx?$/u.test(basename(source))) {
    throw new TypeError("Укажите файл spec/scenario.spec.ts либо spec/scenario.spec.tsx владельца")
  }
  return createScenarioGuide(await readScenario({path: source}))
}
