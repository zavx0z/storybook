import type {HmrSocket} from "./socket"

/**
Контракт повторного подключения транспортной связи страницы.

Вход описывает socket и обработчики событий, выход освобождает их и соединение.
Смысл сообщений остаётся у вызывающего владельца.
*/
export declare namespace HmrConnection {
  /**
  Socket и обработчики жизненного цикла соединения.

  @property socket - Первое соединение, уже созданное владельцем grant. Компонент подключает к нему
  обработчики `open`, `message` и `close` и закрывает его при `dispose`.

  @property [reconnect] - Создаёт новое соединение для сигнала времени жизни. Обычно владелец получает
  новый grant внутри этого callback. Ошибка или отклонение не передаётся наружу: компонент повторяет попытку
  с экспоненциальной задержкой от 250 мс до 2 секунд. Если callback отсутствует, после закрытия socket
  автоматическое подключение не выполняется.

  @property onOpen - Вызывается при открытии каждого подключённого socket; `reconnected` равен `false`
  для исходного соединения и `true` после первой попытки переподключения. Владелец повторно оформляет
  необходимые подписки. Callback вызывается без перехвата исключений.

  @property onMessage - Получает каждое событие `message` подключённого socket, пока lifecycle не завершён.
  Обработчики старого соединения снимаются перед его закрытием; новое соединение использует тот же callback.
  Callback вызывается без перехвата исключений.

  @property onClose - Вызывается при закрытии socket до запуска повторной попытки и повторно после
  отклонения `reconnect`, перед очередной попыткой. Повторный вызов подавляется, пока таймер или создание
  нового соединения уже выполняются. Callback вызывается без перехвата исключений; при исключении
  из события закрытия начальная попытка переподключения не планируется.
  */
  type Input = Readonly<{
    socket: HmrSocket
    reconnect?(signal: AbortSignal): Promise<HmrSocket>
    onOpen(socket: HmrSocket, reconnected: boolean): void
    onMessage(event: MessageEvent): void
    onClose(): void
  }>

  /**
  Завершение подписки на события и текущего соединения.

  @property dispose - Один раз отменяет сигнал повторного подключения, очищает ожидающий таймер,
  снимает обработчики и закрывает текущий socket. Поздно созданный socket закрывается без установки.
  Повторный вызов не выполняет транспортных операций. Ошибка снятия обработчиков или закрытия
  текущего socket передаётся вызывающему коду; сигнал к этому моменту уже отменён.
  */
  type Output = Readonly<{dispose(): void}>
}
