/**
Контракт сериализованной замены одного исполняемого scope страницы.

`Input` описывает освобождение текущего исполнения и создание его восстановления.
`Output` управляет единственным текущим scope; переходы не перезагружают страницу
и не выбирают маршрут или состав Canvas.
*/
export declare namespace HmrPage {
  /**
  Операции владельца исполнения, необходимые для освобождения и восстановления scope.

  @typeParam Scope - Данные, достаточные для повторного создания прежнего исполнения.

  @property [initial] - Уже смонтированный scope при подключении lifecycle. До первой замены он доступен через `current`.

  @property release - Освобождает переданный активный scope и его ресурсы. Вызывается перед каждой заменой,
  при `detach` и `dispose`, а также для не принятого кандидата или неудачного восстановления.
  Ошибка освобождения прерывает переход; ошибка при откате входит в AggregateError операции замены.

  @property restore - Создаёт новый экземпляр прежнего исполнения из сохранённого scope после ошибки кандидата.
  Возвращённый экземпляр становится текущим и передаётся в `accept` с `restored: true`.
  Если восстановление, освобождение кандидата либо принятие восстановленного экземпляра завершается ошибкой,
  замена отклоняется с {@link AggregateError}, содержащим исходную и ошибку отката.
  */
  type Input<Scope> = Readonly<{
    initial?: Scope
    release(scope: Scope): void | Promise<void>
    restore(scope: Scope): Promise<Scope>
  }>

  /**
  Управление текущим scope, его сериализованной заменой и завершением lifecycle.

  @typeParam Scope - Тип активного исполняемого scope.

  @property current - Текущий scope либо `null`, когда прежний уже освобождён и новый ещё не установлен.

  @property replace - Ставит замену в общую очередь. После освобождения текущего scope вызывает `create`;
  принятый результат становится `current`, затем `accept` получает его с `restored: false`.
  При ошибке `create` или `accept` кандидат освобождается, прежнее исполнение восстанавливается через
  {@link HmrPage.Input.restore} и принимается с `restored: true`. Ошибка исходного перехода отклоняет Promise.
  Если откат также завершается ошибкой, Promise отклоняется с {@link AggregateError}, содержащим обе ошибки.
  Вызов после начала `dispose` отклоняется с ошибкой завершённого lifecycle.

  @property detach - Ставит освобождение текущего scope в ту же очередь и делает `current` равным `null`.
  Используется перед передачей страницы другому владельцу платформы; сам по себе не завершает lifecycle,
  поэтому последующая замена остаётся допустимой.

  @property dispose - Сразу запрещает новые замены и ставит окончательное освобождение после уже ожидающих
  операций. Активное создание кандидата, завершившееся после начала закрытия, освобождается и не принимается.
  Повторные вызовы возвращают тот же Promise завершения; ошибка освобождения отклоняет его.
  */
  type Output<Scope> = Readonly<{
    readonly current: Scope | null
    replace(create: () => Promise<Scope>, accept: (scope: Scope, restored: boolean) => void | Promise<void>): Promise<void>
    detach(): Promise<void>
    dispose(): Promise<void>
  }>
}
