import type {Source} from "./source"

/**
Типовая граница чтения документации исходников без исполнения их кода.

{@link Zavx0zStorybookTypedoc.Input} выбирает исходники; {@link Zavx0zStorybookTypedoc.Output}
сохраняет документацию вместе с независимыми фактами сигнатур для сценария проверки.
*/
export declare namespace Zavx0zStorybookTypedoc {
  /**
  Исходники, чьи собственные объявления требуется описать.

  @property paths - Непустой список путей к TypeScript/TSX файлам; относительные пути разрешаются от cwd.
  Импорты помогают компилятору раскрыть символы, но объявления зависимостей не добавляются в результат.
  */
  type Input = Readonly<{paths: readonly string[]}>

  /**
  Документация и сигнатуры одного согласованного чтения.

  @property sources - Исходники в порядке запроса, без повторов физических путей.
  Отсутствующий текст остаётся пустым; это не подтверждение достаточности описания.
  */
  type Output = Readonly<{sources: readonly Source[]}>
}
